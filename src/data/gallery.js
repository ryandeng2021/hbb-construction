const projectsBySlug = new Map(projects.map((project) => [project.slug, project]));

// Helper to build a list of gallery image objects from filenames living in /public/img.
// Each image is automatically linked back to the project it came from (via the filename
// prefix) so the lightbox can offer a "View Full Project" link. Photos are grouped by
// project (newest project first) regardless of the order they're listed below, so each
// project's photos always read together as one consistent set instead of being
// interleaved with photos from other projects.
const buildImages = (categoryLabel, filenames) => {
  const withPrefix = filenames.map((filename) => ({
    filename,
    prefix: Number(filename.split('-')[0])
  }));

  // Stable sort - photos keep their listed order within the same project.
  withPrefix.sort((a, b) => b.prefix - a.prefix);

  return withPrefix.map(({ filename, prefix }, index) => {
    const projectSlug = PREFIX_TO_PROJECT_SLUG[prefix];
    const project = projectSlug ? projectsBySlug.get(projectSlug) : null;

    return {
      id: `${categoryLabel}-${index + 1}`,
      src: getAssetPath(`/img/${filename}`),
      alt: project ? `${project.title} - ${categoryLabel}` : `${categoryLabel} ${index + 1}`,
      project: project
        ? { slug: project.slug, title: project.title, location: project.location }
        : null
    };
  });
};

// Moves a single image (matched by its filename) to the end of an already-built image
// list, overriding the automatic project grouping - useful for bumping a weaker photo
// out of the leading spot without reshuffling the rest of the set.
const moveToEnd = (images, filename) => {
  const index = images.findIndex((image) => image.src.endsWith(filename));
  if (index === -1) return images;
  const [image] = images.splice(index, 1);
  images.push(image);
  return images;
};

