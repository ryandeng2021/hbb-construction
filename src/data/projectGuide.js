export function findGuideAnswers(input, topic) {
  const normalized = input.toLowerCase().normalize('NFKC').replace(/[’']/g, '').replace(/\s+/g,' ').trim();
  if(!normalized) return [];
  return guideQuestions.map(question => {
    const exact = question.question.toLowerCase().replace(/[’']/g,'') === normalized;
    const hits = question.terms.filter(term => normalized.includes(term));
    return {question, score: exact ? 1000 : hits.length ? Math.max(...hits.map(term=>term.length)) + (question.topic===topic ? 2 : 0) : 0};
  }).filter(item=>item.score>0).sort((a,b)=>b.score-a.score).map(item=>item.question);
}
